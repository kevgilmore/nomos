import { readdir, readFile, rename, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const workspaceRoot = path.resolve(import.meta.dirname, "../../../..");
const appsDirectory = path.join(workspaceRoot, "apps");
const outputPath = path.join(workspaceRoot, "platform", "data", "src", "apps.generated.ts");
const uiOutputPath = path.join(workspaceRoot, "platform", "ui", "src", "nomos-apps.generated.ts");

export async function syncAppRegistry() {
  const entries = await readdir(appsDirectory, { withFileTypes: true });
  const apps = [];

  for (const entry of entries) {
    if (!entry.isDirectory()) continue;

    const manifestPath = path.join(appsDirectory, entry.name, "app.manifest.json");
    let manifest;
    try {
      manifest = JSON.parse(await readFile(manifestPath, "utf8"));
    } catch (error) {
      if (error?.code === "ENOENT") continue;
      throw new Error(`Could not read apps/${entry.name}/app.manifest.json`, { cause: error });
    }

    if (manifest.discoverable === false) continue;
    if (typeof manifest.slug !== "string" || typeof manifest.name !== "string" || typeof manifest.href !== "string") {
      throw new Error(`apps/${entry.name}/app.manifest.json must define string values for slug, name, and href.`);
    }
    const productionHref = typeof manifest.productionHref === "string" ? manifest.productionHref : manifest.slug === "home" ? "https://nomos.codes" : `https://${manifest.slug}.nomos.codes`;
    if (!/^https:\/\/(?:[a-z0-9-]+\.)?nomos\.codes(?:\/|$)/.test(productionHref)) {
      throw new Error(`apps/${entry.name}/app.manifest.json productionHref must use an https nomos.codes host.`);
    }

    apps.push({
      slug: manifest.slug,
      name: manifest.name,
      href: manifest.href,
      productionHref,
      icon: typeof manifest.icon === "string" ? manifest.icon : "app",
    });
  }

  apps.sort((left, right) => left.name.localeCompare(right.name));
  const source = `// Generated by scripts/sync-app-registry.mjs. Do not edit by hand.\n` +
    `export type PlatformApp = { slug: string; name: string; href: string; productionHref: string; icon: string };\n` +
    `export const platformApps: PlatformApp[] = ${JSON.stringify(apps, null, 2)};\n`;

  const temporaryOutputPath = `${outputPath}.${process.pid}.tmp`;
  await writeFile(temporaryOutputPath, source);
  await rename(temporaryOutputPath, outputPath);
  const uiSource = `// Generated by scripts/sync-app-registry.mjs. Do not edit by hand.\n` +
    `export type NomosGeneratedApp = { slug: string; label: string; localHref: string; productionHref: string; icon: string };\n` +
    `export const generatedNomosApps: NomosGeneratedApp[] = ${JSON.stringify(apps.map((app) => ({ slug: app.slug, label: app.name, localHref: app.href, productionHref: app.productionHref, icon: app.icon })), null, 2)};\n`;
  const uiTemporaryOutputPath = `${uiOutputPath}.${process.pid}.tmp`;
  await writeFile(uiTemporaryOutputPath, uiSource);
  await rename(uiTemporaryOutputPath, uiOutputPath);
  return apps;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const apps = await syncAppRegistry();
  console.log(`Registered ${apps.length} discoverable app${apps.length === 1 ? "" : "s"}.`);
}
